fn glyph(c: char) -> &'static Glyph {
    let c = c.to_ascii_uppercase();
    let find = |c: char| GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| rows);
    find(c)
        .or_else(|| find('?'))
        .expect("the font has a ? glyph")
}

/// Width in pixels of `text` (no trailing gap).
pub fn text_width(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        n * ADVANCE - 1
    }
}

/// Draw `text` into a `buf_w`-pixel-wide picture with its top-left corner at (`x`, `y`).
/// Pixels outside the picture are clipped.
pub fn draw_text(buf: &mut [u32], buf_w: usize, x: i32, y: i32, text: &str, colour: u32) {
    let buf_h = buf.len() / buf_w;
    for (i, c) in text.chars().enumerate() {
        let gx = x + (i * ADVANCE) as i32;
        for (row, line) in glyph(c).iter().enumerate() {
            for (col, px) in line.bytes().enumerate() {
                if px != b'#' {
                    continue;
                }
                let (px_x, px_y) = (gx + col as i32, y + row as i32);
                if px_x >= 0 && px_y >= 0 && (px_x as usize) < buf_w && (px_y as usize) < buf_h {
                    buf[px_y as usize * buf_w + px_x as usize] = colour;
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_5_by_7_and_unique() {
        for (i, (c, rows)) in GLYPHS.iter().enumerate() {
            for row in rows {
                assert_eq!(row.len(), GLYPH_W, "glyph {c:?}");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "glyph {c:?}");
            }
            assert!(
                GLYPHS[..i].iter().all(|(o, _)| o != c),
                "glyph {c:?} is defined twice"
            );
        }
    }

    #[test]
    fn letters_and_digits_are_not_blank_and_are_all_different() {
        let set: Vec<char> = ('A'..='Z').chain('0'..='9').collect();
        for (i, a) in set.iter().enumerate() {
            assert!(glyph(*a).iter().any(|r| r.contains('#')), "{a} is blank");
            for b in &set[i + 1..] {
                assert_ne!(glyph(*a), glyph(*b), "{a} and {b} look the same");
            }
        }
    }

    #[test]
    fn lower_case_and_unknown_characters() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('é'), glyph('?'));
    }

    #[test]
    fn draws_the_letter_a_where_asked() {
        let mut buf = vec![0u32; 8 * 8];
        draw_text(&mut buf, 8, 1, 0, "A", 7);
        let art: Vec<String> = buf
            .chunks(8)
            .take(3)
            .map(|r| r.iter().map(|&p| if p == 7 { '#' } else { '.' }).collect())
            .collect();
        assert_eq!(art, ["..###...", ".#...#..", ".#...#.."]);
    }

    #[test]
    fn drawing_outside_the_picture_is_clipped_not_a_panic() {
        let mut buf = vec![0u32; 4 * 4];
        draw_text(&mut buf, 4, -3, -3, "AB", 1);
        draw_text(&mut buf, 4, 2, 2, "WWW", 1);
        draw_text(&mut buf, 4, 100, 100, "X", 1);
        assert!(buf.contains(&1));
    }

    #[test]
    fn widths() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("A"), 5);
        assert_eq!(text_width("AB"), 11);
    }
}
